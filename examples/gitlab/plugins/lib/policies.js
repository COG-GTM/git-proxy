/**
 * Pure policy helpers shared by the example GitLab plugins. Nothing in this file depends on
 * GitProxy, so the allow/deny logic can be unit tested (or reused) in isolation.
 */

/** Jira-style key (PAY-123) or GitLab issue reference (#42, group/project#42). */
export const DEFAULT_TICKET_PATTERN = '\\b[A-Z][A-Z0-9]+-\\d+\\b|#\\d+\\b';

/** Merge commits generated by git or by GitLab when an MR is merged. */
export const MERGE_COMMIT_PATTERN = /^Merge (branch|remote-tracking branch|tag|commit) /;

export const DEFAULT_PROTECTED_BRANCHES = ['main', 'master', 'release/*'];

/**
 * Split a comma (or whitespace) separated list, e.g. from an environment variable.
 * @param {string | undefined} value raw value
 * @param {string[]} fallback returned when value is empty or undefined
 * @return {string[]} trimmed, non-empty entries
 */
export function parseList(value, fallback = []) {
  if (!value || !value.trim()) {
    return fallback;
  }
  return value
    .split(/[,\s]+/)
    .map((entry) => entry.trim())
    .filter(Boolean);
}

/**
 * @param {string | undefined} message commit message
 * @return {string} the first line of the commit message
 */
export function subjectLine(message) {
  return (message ?? '').split('\n')[0].trim();
}

/**
 * Return the commits whose message does not reference a ticket. Merge commits are exempt.
 * @param {Array<{message?: string}>} commits action.commitData
 * @param {string} ticketPattern regular expression source
 * @return {Array<{message?: string}>} offending commits
 */
export function findCommitsMissingTicket(commits, ticketPattern = DEFAULT_TICKET_PATTERN) {
  const ticket = new RegExp(ticketPattern);
  return (commits ?? []).filter((commit) => {
    const message = commit.message ?? '';
    return !MERGE_COMMIT_PATTERN.test(message) && !ticket.test(message);
  });
}

/**
 * Convert a simple branch glob into an anchored RegExp.
 * `*` matches within one path segment, `**` matches across segments.
 * @param {string} glob e.g. release/*
 * @return {RegExp} anchored regular expression
 */
export function globToRegExp(glob) {
  let source = '';
  for (let i = 0; i < glob.length; i++) {
    const char = glob[i];
    if (char === '*' && glob[i + 1] === '*') {
      source += '.*';
      i++;
    } else if (char === '*') {
      source += '[^/]+';
    } else if (char === '?') {
      source += '[^/]';
    } else {
      source += char.replace(/[.+^${}()|[\]\\]/g, '\\$&');
    }
  }
  return new RegExp(`^${source}$`);
}

/**
 * @param {string | undefined} ref e.g. refs/heads/main
 * @return {string} the short branch name, e.g. main
 */
export function branchName(ref) {
  return (ref ?? '').replace(/^refs\/heads\//, '');
}

/**
 * @param {string | undefined} ref pushed ref, e.g. refs/heads/release/1.2
 * @param {string[]} patterns branch globs
 * @return {string | null} the first matching pattern, or null when the branch is not protected
 */
export function matchProtectedBranch(ref, patterns = DEFAULT_PROTECTED_BRANCHES) {
  const name = branchName(ref);
  return patterns.find((pattern) => globToRegExp(pattern).test(name)) ?? null;
}

/**
 * Normalise a repository URL or group reference to `host/path` without protocol or `.git`.
 * @param {string | undefined} url e.g. https://gitlab.com/acme/platform/api.git
 * @return {string} e.g. gitlab.com/acme/platform/api
 */
export function normaliseRepoPath(url) {
  return (url ?? '')
    .trim()
    .replace(/^[a-z]+:\/\//i, '')
    .replace(/\.git$/, '')
    .replace(/\/+$/, '')
    .toLowerCase();
}

/**
 * Find the restricted group (`host/group[/subgroup]`) a repository belongs to.
 * @param {string | undefined} url repository URL (action.url)
 * @param {string[]} groups restricted groups
 * @return {string | null} matching group, or null
 */
export function matchRestrictedGroup(url, groups) {
  const repoPath = normaliseRepoPath(url);
  return (
    groups.find((group) => {
      const groupPath = normaliseRepoPath(group);
      return groupPath !== '' && repoPath.startsWith(`${groupPath}/`);
    }) ?? null
  );
}

/**
 * Extract the username from an HTTP Basic Authorization header. The password (a GitLab PAT) is
 * never returned.
 * @param {string | undefined} header Authorization header value
 * @return {string | null} username, or null when absent / not Basic auth
 */
export function basicAuthUsername(header) {
  if (typeof header !== 'string' || !/^basic /i.test(header)) {
    return null;
  }
  const decoded = Buffer.from(header.slice(6).trim(), 'base64').toString('utf8');
  const separator = decoded.indexOf(':');
  const username = separator === -1 ? decoded : decoded.slice(0, separator);
  return username || null;
}
